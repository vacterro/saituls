<#
.SYNOPSIS
    Installs or updates the SAITULS\SAI Accounts Keeper scheduled task.

.DESCRIPTION
    One canonical task for the whole SAI Accounts plane. It runs the
    INSTALLED engine -- C:\ProgramData\SAI\Accounts\bin\sai-accounts.exe,
    never a repository checkout path -- as:

        sai-accounts autoconnect --budget-ms <BudgetMs>

    at user logon and every IntervalMinutes (default 2) while the session
    exists, so managed account contexts are reconciled while SAITULS is
    closed. The task owns no account state; autoconnect is idempotent and
    restores only ENABLED managed accounts with auto_connect == true.

    Never one task per account, never a second GUI process, never an
    interactive IDE window: autoconnect only brings up the headless broker.
    The action runs through wscript with a fixed VBS launcher, because
    sai-accounts.exe is a console application and Task Scheduler never hides
    a console child: launching it directly -- or through PowerShell's
    -WindowStyle Hidden -- flashes a console window and steals the foreground
    on every cadence, minimizing fullscreen apps (T-284, T-301).

    Task Scheduler is told not to start a second instance (IgnoreNew), and
    the engine holds a named autoconnect mutex as well: two independent
    guards, because the live SAITULS timer may fire the same sweep at the
    same moment.

.EXAMPLE
    .\Scripts\accounts\Install-SaiAccountsKeeper.ps1 -Enable
    .\Scripts\accounts\Install-SaiAccountsKeeper.ps1 -VerifyOnly
    .\Scripts\accounts\Install-SaiAccountsKeeper.ps1 -Disable
    .\Scripts\accounts\Install-SaiAccountsKeeper.ps1 -Remove
#>
[CmdletBinding(SupportsShouldProcess = $true)]
param(
    # Install/enable the task and run one immediate reconciliation.
    [switch]$Enable,
    # Disable the periodic task. Running brokers are left alone and no
    # per-account auto_connect value is touched: OFF means "do not heal
    # in the background", not "disconnect everything now".
    [switch]$Disable,
    # Unregister the task and exit.
    [switch]$Remove,
    # Report what is registered and whether it matches; change nothing.
    [switch]$VerifyOnly,
    # Bounded reconciliation budget passed to autoconnect (30s..120s).
    [int]$BudgetMs = 90000,
    # Keeper cadence in minutes (1..5). Default 2.
    [int]$IntervalMinutes = 2,
    # Canonical task identity. Overridable only so tests can prove the
    # installer against a scratch name; production always uses the default.
    [string]$TaskPath = '\SAITULS\',
    [string]$TaskName = 'SAI Accounts Keeper',
    # The engine the task invokes. Defaults to the canonical install;
    # overridable for the same test reason as the task name.
    [string]$EngineExe = '',
    # Skip the immediate reconciliation after -Enable (tests only).
    [switch]$NoRun
)

$ErrorActionPreference = 'Stop'

if (-not $EngineExe) {
    $EngineExe = Join-Path $env:ProgramData 'SAI\Accounts\bin\sai-accounts.exe'
}
# Windowless host for the task action. Task Scheduler never hides a console
# child, and the engine is a console application. A PowerShell host with
# -WindowStyle Hidden is NOT enough: measured here, its console window is
# created visible, takes the foreground for ~20ms at every cadence and hides
# itself afterwards -- enough to minimize a fullscreen game every 2 minutes.
# wscript is a GUI-subsystem host and WScript.Shell.Run(..., 0, ...) creates the
# engine with SW_HIDE from the start, so no console window is ever mapped.
# Resolved from the OS folder, not from PATH.
$KeeperHostExe = Join-Path $env:SystemRoot 'System32\wscript.exe'
$KeeperLauncher = Join-Path (Split-Path -Parent $EngineExe) 'sai-accounts-keeper.vbs'
$FullName = $TaskPath + $TaskName

# The launcher is fixed text: canonical engine path, fixed verb, fixed budget.
# It carries no operator input and no credential, and it is rewritten only when
# its bytes differ so re-running the installer is idempotent.
function Get-KeeperLauncherText([string]$EnginePath, [int]$Budget) {
    $engineLiteral = $EnginePath.Replace('"', '""')
    $q = [string][char]34
    # Explicit CRLF and explicit quote counts keep the bytes identical no
    # matter which editor or line-ending policy touched this script.
    return "' Generated by Install-SaiAccountsKeeper.ps1. Do not edit.`r`n" +
        "CreateObject(" + $q + "WScript.Shell" + $q + ").Run " + ($q * 3) + $engineLiteral + ($q * 2) +
        " autoconnect --budget-ms $Budget" + $q + ", 0, False"
}

function Write-KeeperLauncher([string]$EnginePath, [int]$Budget) {
    $text = Get-KeeperLauncherText $EnginePath $Budget
    $current = $null
    if (Test-Path -LiteralPath $KeeperLauncher -PathType Leaf) {
        $current = Get-Content -Raw -LiteralPath $KeeperLauncher
    }
    if ($current -ne $text) {
        Set-Content -LiteralPath $KeeperLauncher -Value $text -Encoding ASCII -NoNewline
    }
}

function Get-KeeperTask {
    return Get-ScheduledTask -TaskPath $TaskPath -TaskName $TaskName -ErrorAction SilentlyContinue
}

if (-not (Get-Command Register-ScheduledTask -ErrorAction SilentlyContinue)) {
    throw 'The ScheduledTasks module is unavailable; cannot register the SAI Accounts keeper.'
}
if ($BudgetMs -lt 30000 -or $BudgetMs -gt 120000) {
    throw "BudgetMs must be between 30000 and 120000 (got $BudgetMs)."
}
if ($IntervalMinutes -lt 1 -or $IntervalMinutes -gt 5) {
    throw "IntervalMinutes must be between 1 and 5 (got $IntervalMinutes)."
}

# ------------------------------------------------------------------- removal

if ($Remove) {
    $existing = Get-KeeperTask
    if (-not $existing) {
        Write-Host "Nothing to remove: $FullName is not registered."
        exit 0
    }
    if ($PSCmdlet.ShouldProcess($FullName, 'Unregister scheduled task')) {
        try {
            Unregister-ScheduledTask -TaskPath $TaskPath -TaskName $TaskName -Confirm:$false
        } catch {
            if ($_.Exception.Message -match 'Access is denied|0x80070005') {
                throw "ELEVATION_REQUIRED: removing $FullName needs elevation. Re-run from an elevated prompt."
            }
            throw
        }
        Write-Host "Removed $FullName. Account brokers and per-account settings were left untouched."
        if (Test-Path -LiteralPath $KeeperLauncher -PathType Leaf) {
            Remove-Item -LiteralPath $KeeperLauncher -Force -ErrorAction SilentlyContinue
        }
    }
    exit 0
}

# ------------------------------------------------------------------- disable

if ($Disable) {
    $existing = Get-KeeperTask
    if (-not $existing) {
        Write-Host "Nothing to disable: $FullName is not registered."
        exit 0
    }
    if ($PSCmdlet.ShouldProcess($FullName, 'Disable scheduled task')) {
        try {
            Disable-ScheduledTask -TaskPath $TaskPath -TaskName $TaskName | Out-Null
        } catch {
            if ($_.Exception.Message -match 'Access is denied|0x80070005') {
                throw "ELEVATION_REQUIRED: disabling $FullName needs elevation. Re-run from an elevated prompt."
            }
            throw
        }
        Write-Host "Disabled $FullName. Running brokers stay online; per-account auto_connect is unchanged."
    }
    exit 0
}

# --------------------------------------------------------------- verification

# Everything the task must satisfy, checked against what is actually
# registered rather than against what this script intended to register.
function Assert-KeeperTask {
    $task = Get-KeeperTask
    if (-not $task) { throw "Not registered: $FullName" }

    $action = @($task.Actions)[0]
    if (@($task.Actions).Count -ne 1) { throw "Definition drift: expected exactly one action, found $(@($task.Actions).Count)" }
    if ($action.Execute -ne $KeeperHostExe) {
        throw "Action drift: expected windowless host $KeeperHostExe, found $($action.Execute)"
    }
    $expectedArgs = "//B //NoLogo `"$KeeperLauncher`""
    if ($action.Arguments -ne $expectedArgs) {
        throw "Action drift: expected '$expectedArgs', found '$($action.Arguments)'"
    }
    # The task now names a launcher, so the launcher itself is part of the
    # definition: a missing or edited file would silently change what the
    # keeper executes. Pin its exact bytes to the canonical engine and verb.
    if (-not (Test-Path -LiteralPath $KeeperLauncher -PathType Leaf)) {
        throw "Launcher drift: $KeeperLauncher is missing"
    }
    $launcherExpected = Get-KeeperLauncherText $EngineExe $BudgetMs
    $launcherActual = Get-Content -Raw -LiteralPath $KeeperLauncher
    if ($launcherActual -ne $launcherExpected) {
        throw "Launcher drift: $KeeperLauncher does not name the canonical engine and fixed verb"
    }
    # The task must invoke only the fixed reconciliation action through the
    # windowless host: no script, no checkout path, no credential-shaped
    # argument may ever arrive here. The launcher file is the one script the
    # definition is allowed to name; the engine path lives inside it and is
    # pinned by the byte comparison above.
    $commandLine = $action.Execute + ' ' + $action.Arguments
    foreach ($bad in @('.ps1', '.cmd', '.bat', '\Scripts\', 'sai-accounts-helper')) {
        if ($commandLine.IndexOf($bad, [StringComparison]::OrdinalIgnoreCase) -ge 0) {
            throw "Action drift: task definition references '$bad', which the keeper action must never contain"
        }
    }
    foreach ($secret in @('password', 'token', 'secret', 'credential', 'apikey', 'privatekey')) {
        if ($action.Arguments.IndexOf($secret, [StringComparison]::OrdinalIgnoreCase) -ge 0) {
            throw "Action drift: task arguments carry credential-shaped text ('$secret')"
        }
    }

    $logon = @($task.Triggers | Where-Object { $_.CimClass.CimClassName -eq 'MSFT_TaskLogonTrigger' })
    if ($logon.Count -eq 0) { throw 'Trigger drift: no logon trigger' }

    # The repetition MUST sit on a time trigger. A repeating logon trigger
    # passes a naive "is there repetition?" check while never firing in the
    # session that enabled the keeper, so the drift this verifier has to catch
    # is precisely repetition-on-the-logon-trigger.
    $repeating = @($task.Triggers | Where-Object {
        $_.Repetition -and $_.Repetition.Interval -and
        $_.CimClass.CimClassName -ne 'MSFT_TaskLogonTrigger'
    })
    if ($repeating.Count -eq 0) {
        throw 'Trigger drift: no in-session repeating time trigger; periodic reconciliation would not start until the next logon'
    }
    $requested = New-TimeSpan -Minutes $IntervalMinutes
    foreach ($t in $repeating) {
        $observed = $null
        try { $observed = [System.Xml.XmlConvert]::ToTimeSpan($t.Repetition.Interval) } catch { }
        $observedText = if ($null -ne $observed) { '{0:hh\:mm\:ss}' -f $observed } else { $t.Repetition.Interval }
        if ($null -eq $observed -or $observed -ne $requested) {
            throw ("Cadence drift: expected {0:hh\:mm\:ss}, observed {1}" -f $requested, $observedText)
        }
    }

    if ($task.Settings.MultipleInstances -ne 'IgnoreNew') {
        throw "Concurrency drift: MultipleInstances is $($task.Settings.MultipleInstances), expected IgnoreNew"
    }
    if (-not $task.Settings.Hidden) { throw 'Settings drift: the task is not hidden' }
    if (-not $task.Settings.StartWhenAvailable) {
        throw 'Settings drift: StartWhenAvailable is off, so a missed run after a reboot never happens'
    }
    if ($task.Settings.ExecutionTimeLimit -ne 'PT0S' -and $task.Settings.ExecutionTimeLimit) {
        throw "Settings drift: ExecutionTimeLimit is $($task.Settings.ExecutionTimeLimit), expected none"
    }
    if ($task.Settings.DisallowStartIfOnBatteries) {
        throw 'Settings drift: DisallowStartIfOnBatteries is on'
    }

    foreach ($p in @($task.Principal)) {
        if ($p.RunLevel -ne 'Limited') {
            throw "Privilege drift: task RunLevel is $($p.RunLevel), expected Limited"
        }
    }

    if ($task.State -eq 'Disabled') { throw "State drift: $FullName is registered but disabled" }

    return @{
        Task    = $task
        Command = $action.Execute + ' ' + $action.Arguments
    }
}

if ($VerifyOnly) {
    $report = Assert-KeeperTask
    Write-Host "PASS: $FullName reconciles every $IntervalMinutes minute(s) at logon."
    Write-Host "  $($report.Command)"
    exit 0
}

# --------------------------------------------------------------- installation

if (-not $Enable -and -not $Disable -and -not $Remove -and -not $VerifyOnly) {
    # No switch: enable. The keeper is a toggle; naming no direction means ON.
    $Enable = $true
}

if ($Enable) {
    if (-not (Test-Path -LiteralPath $EngineExe -PathType Leaf)) {
        throw "The canonical engine is not installed: $EngineExe. Install SAI Accounts before enabling the keeper."
    }

    # Windowless host: the engine is a console application, and Task
    # Scheduler does not hide a console child. PowerShell's -WindowStyle
    # Hidden still maps its console window first and only hides it afterwards
    # (measured: foreground taken for ~20ms every cadence, T-284/T-301), so
    # the task runs a fixed VBS launcher under wscript instead; WScript.Shell
    # Run with window style 0 creates the engine with SW_HIDE from the start.
    # The reconciliation output is not needed anywhere outside the engine's
    # own keeper log.
    Write-KeeperLauncher $EngineExe $BudgetMs
    $action = New-ScheduledTaskAction -Execute $KeeperHostExe `
        -Argument "//B //NoLogo `"$KeeperLauncher`""

    # TWO triggers, and the split is load-bearing. Repetition lives on a TIME
    # trigger, never on the logon trigger: a logon trigger's repetition is only
    # armed once the trigger itself fires, so a keeper enabled mid-session
    # (the normal case -- the operator just flipped the toggle) would sit armed
    # and idle until the NEXT logon. Measured on this host: task State=Ready,
    # LastTaskResult=0x41303 (SCHED_S_TASK_HAS_NOT_RUN), NextRunTime=null, and
    # a deliberately killed broker stayed dead through five cadences.
    #
    # So: the time trigger, anchored one minute in the past so it is already
    # due, carries the repetition and begins healing this session; the bare
    # logon trigger adds the immediate run at every logon. Both invoke the same
    # idempotent autoconnect, so the overlap at logon is harmless by construction.
    $logonTrigger = New-ScheduledTaskTrigger -AtLogOn
    $span = New-TimeSpan -Minutes $IntervalMinutes
    # Ten years, not [TimeSpan]::MaxValue: MaxValue serializes as
    # P99999999DT23H59M59S, which Register-ScheduledTask rejects as out of
    # range (0x80041318). Ten years is indefinite for a keeper that
    # re-registers itself on every toggle and repair.
    $repeatTrigger = $null
    try {
        $repeatTrigger = New-ScheduledTaskTrigger -Once -At (Get-Date).AddMinutes(-1) `
            -RepetitionInterval $span -RepetitionDuration (New-TimeSpan -Days 3650)
    } catch {
        throw 'Could not build a repeating trigger on this Windows build.'
    }
    $trigger = @($logonTrigger, $repeatTrigger)

    $settings = New-ScheduledTaskSettingsSet `
        -MultipleInstances IgnoreNew `
        -Hidden `
        -StartWhenAvailable `
        -AllowStartIfOnBatteries `
        -DontStopIfGoingOnBatteries `
        -ExecutionTimeLimit ([TimeSpan]::Zero)

    # Least privilege: the operator's own interactive logon, never elevated.
    # Registering this needs no admin rights; if it fails the caller reports
    # "keeper unavailable" and the GUI keeps working without it.
    $me = "$env:USERDOMAIN\$env:USERNAME"
    $principal = New-ScheduledTaskPrincipal -UserId $me -LogonType Interactive -RunLevel Limited

    $description = 'SAI Accounts keeper: reconciles managed account brokers ' +
        "(autoconnect) at logon and every $IntervalMinutes minute(s). Owns no account state."

    if ($PSCmdlet.ShouldProcess($FullName, 'Register scheduled task')) {
        # Transactional replacement: capture the complete existing definition
        # and restore it on any post-destructive failure; with no prior task
        # a failure leaves nothing half-registered.
        $prior = Get-KeeperTask
        $priorBackup = $null
        if ($prior) {
            try {
                $priorBackup = @{
                    Xml = Export-ScheduledTask -TaskPath $TaskPath -TaskName $TaskName -ErrorAction Stop
                }
                if ([string]::IsNullOrWhiteSpace($priorBackup.Xml)) {
                    throw 'Empty rollback snapshot'
                }
                $snapshot = [xml]$priorBackup.Xml
                if (-not $snapshot.Task.Actions -or -not $snapshot.Task.Principals -or
                    -not $snapshot.Task.Settings) {
                    throw 'Incomplete rollback snapshot'
                }
                if (@($snapshot.Task.Principals.Principal | Where-Object {
                    $_.LogonType -in @('Password', 'InteractiveTokenOrPassword')
                }).Count) {
                    throw 'Rollback credentials unavailable for password task'
                }
            } catch {
                throw "Cannot capture complete prior task snapshot; replacement refused: $($_.Exception.Message)"
            }
        }
        if ($prior) {
            try {
                Unregister-ScheduledTask -TaskPath $TaskPath -TaskName $TaskName -Confirm:$false
            } catch {
                if ($_.Exception.Message -match 'Access is denied|0x80070005') {
                    throw "ELEVATION_REQUIRED: replacing $FullName needs elevation. Re-run with -Enable from an elevated prompt, or use the Repair action in SAITULS."
                }
                throw
            }
        }
        try {
            Register-ScheduledTask -TaskPath $TaskPath -TaskName $TaskName `
                -Action $action -Trigger $trigger -Settings $settings -Principal $principal `
                -Description $description | Out-Null
            # Prove the registration actually matches before reporting success.
            $report = Assert-KeeperTask
            Write-Host "Registered $FullName at logon and every $IntervalMinutes minute(s)."
            Write-Host "  $($report.Command)"
        } catch {
            $replacementError = $_
            if ($replacementError.Exception.Message -match 'Access is denied|0x80070005') {
                # Nothing was destroyed on this path: the failure happened
                # before or inside the first destructive step.
                throw "ELEVATION_REQUIRED: registering $FullName needs elevation. Re-run with -Enable from an elevated prompt, or use the Repair action in SAITULS."
            }
            $cleanupError = $null
            try {
                if (Get-KeeperTask) { Unregister-ScheduledTask -TaskPath $TaskPath -TaskName $TaskName -Confirm:$false }
            } catch { $cleanupError = $_ }
            if ($priorBackup) {
                try {
                    Register-ScheduledTask -TaskPath $TaskPath -TaskName $TaskName `
                        -Xml $priorBackup.Xml | Out-Null
                } catch {
                    $rollbackError = $_
                    throw "Replacement failed ($($replacementError.Exception.Message)) and restoring the previous task also failed: $($rollbackError.Exception.Message)"
                }
            }
            if ($cleanupError) {
                throw "Replacement failed ($($replacementError.Exception.Message)) and removing the partial task also failed: $($cleanupError.Exception.Message)"
            }
            throw $replacementError
        }
    }

    if (-not $NoRun) {
        # The operator turned the keeper on: reconcile once now, so an
        # already-missing broker does not wait a full cadence.
        $immediate = & $EngineExe autoconnect --budget-ms $BudgetMs 2>&1 | Out-String
        $code = $LASTEXITCODE
        try {
            $env_line = ($immediate -split "`n" | Where-Object { $_.Trim().StartsWith('{') } | Select-Object -Last 1)
            $rep = $env_line | ConvertFrom-Json
            Write-Host ("Immediate reconciliation: {0} started, {1} already online, {2} failed." -f $rep.started, $rep.already_online, $rep.failed)
        } catch {
            Write-Host "Immediate reconciliation exited $code."
        }
        if ($code -gt 2) { throw "Immediate reconciliation failed (exit $code)." }
    }
}
